function renderCurrentRoute(hash) {
  if (hash === "#/" || hash === "") {
    renderHome();
    return "";
  } else if (hash === "#/projects") {
    renderProjects();
    return "";
  } else if (hash === "#/about") {
    renderAbout();
    return "";
  } else if (hash.startsWith("#/case/")) {
    renderCase(hash.replace("#/case/", ""));
    return "";
  } else if (hash === "#projects") {
    renderHome();
    return "#projects";
  } else if (hash === "#about-preview") {
    renderHome();
    return "#about-preview";
  } else {
    renderNotFound();
    return "";
  }
}

function route() {
  const isInitialRender = !hasRendered;
  const hash = isInitialRender && ["#projects", "#about-preview"].includes(window.location.hash)
    ? "#/"
    : window.location.hash || "#/";
  document.body.classList.toggle("is-home-route", ["#/", "#projects", "#about-preview"].includes(hash));
  document.body.classList.toggle("is-work-route", hash === "#/projects");

  document.querySelectorAll("[data-nav-link]").forEach((link) => {
    const isActive = link.dataset.navLink === "work" && hash === "#/projects";
    link.classList.toggle("is-active", isActive);
    if (isActive) {
      link.setAttribute("aria-current", "page");
    } else {
      link.removeAttribute("aria-current");
    }
  });

  if (isInitialRender && hash === "#/" && ["#projects", "#about-preview"].includes(window.location.hash)) {
    history.replaceState(null, "", `${window.location.pathname}${window.location.search}#/`);
  }

  const render = () => {
    const scrollTarget = renderCurrentRoute(hash);
    requestAnimationFrame(() => {
      makeLinksSentenceCase();
      setupAccordions();
      setupMotion();
      setupProjectShowcaseHover();
      setupTestimonials();
      setupHoverLinkPreviews();
      app.classList.remove("is-changing");
      caseNavLockHref = "";
      clearTimeout(caseNavLockTimer);
      if (scrollTarget && !isInitialRender) {
        document.querySelector(scrollTarget)?.scrollIntoView({ behavior: hasRendered ? "smooth" : "auto" });
      } else if (hasRendered) {
        window.scrollTo({ top: 0, behavior: "auto" });
      } else {
        window.scrollTo({ top: 0, behavior: "auto" });
      }
      requestCaseSidebarSync();
      hasRendered = true;
    });
  };

  clearTimeout(routeTimer);
  if (!hasRendered) {
    render();
    return;
  }

  app.classList.add("is-changing");
  routeTimer = setTimeout(render, 180);
}

function toSentenceCase(str) {
  if (!str) return str;
  const s = String(str).trim().toLowerCase();
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function makeLinksSentenceCase() {
  const selectors = [
    '.site-footer nav a',
    '.case-section-nav a',
    '.case-description-nav a',
    '.underline-link'
  ];
  const nodes = document.querySelectorAll(selectors.join(','));
  nodes.forEach((a) => {
    if (!a || a.dataset._caseNormalized || a.dataset.preserveLabel) return;
    if (a.querySelector('img, svg')) return;
    const text = a.textContent || '';
    const normalized = toSentenceCase(text);
    if (normalized && normalized !== text) a.textContent = normalized;
    a.dataset._caseNormalized = '1';
  });
}

