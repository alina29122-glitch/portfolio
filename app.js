function renderCurrentRoute(hash) {
  if (hash === "#/" || hash === "") {
    renderHome();
    return false;
  } else if (hash === "#/about") {
    renderAbout();
    return false;
  } else if (hash.startsWith("#/case/")) {
    renderCase(hash.replace("#/case/", ""));
    return false;
  } else if (hash === "#projects") {
    renderHome();
    return true;
  } else {
    renderNotFound();
    return false;
  }
}

function route() {
  const hash = window.location.hash || "#/";
  const render = () => {
    const shouldScrollToProjects = renderCurrentRoute(hash);
    requestAnimationFrame(() => {
      setupMotion();
      app.classList.remove("is-changing");
      if (shouldScrollToProjects) {
        document.querySelector("#projects")?.scrollIntoView({ behavior: hasRendered ? "smooth" : "auto" });
      } else if (hasRendered) {
        window.scrollTo({ top: 0, behavior: "auto" });
      }
      hasRendered = true;
    });
  };

  clearTimeout(routeTimer);
  if (!hasRendered) {
    render();
    return;
  }

  app.classList.add("is-changing");
  routeTimer = setTimeout(render, 180);
}

function setupMotion() {
  revealObserver?.disconnect();
  const targets = [...app.querySelectorAll(motionQuery)].filter((target) => !target.closest(".hero"));

  if (!("IntersectionObserver" in window)) {
    targets.forEach((target) => target.classList.add("is-visible"));
    return;
  }

  targets.forEach((target, index) => {
    target.classList.add("motion-item");
    target.style.transitionDelay = `${Math.min(index % 4, 3) * 60}ms`;
  });

  revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      revealObserver.unobserve(entry.target);
    });
  }, {
    rootMargin: "0px 0px 16% 0px",
    threshold: 0.04
  });

  targets.forEach((target) => {
    if (target.getBoundingClientRect().top < window.innerHeight) {
      target.classList.add("is-visible");
      return;
    }
    revealObserver.observe(target);
  });
  setupProjectCursor();
}

function setupProjectCursor() {
  if (matchMedia("(pointer: coarse)").matches) return;

  let bubble = document.querySelector(".cursor-bubble");
  if (!bubble) {
    bubble = document.createElement("div");
    bubble.className = "cursor-bubble";
    bubble.textContent = "read more";
    document.body.appendChild(bubble);
    document.body.classList.add("has-cursor-bubble");
  }

  app.querySelectorAll(".project-media").forEach((media) => {
    media.addEventListener("pointerenter", () => bubble.classList.add("is-active"));
    media.addEventListener("pointerleave", () => bubble.classList.remove("is-active"));
    media.addEventListener("pointermove", (event) => {
      bubble.style.left = `${event.clientX}px`;
      bubble.style.top = `${event.clientY}px`;
    });
  });
}

function closeMenu() {
  document.body.classList.remove("menu-open");
  menuButton?.setAttribute("aria-expanded", "false");
  menuOverlay?.setAttribute("aria-hidden", "true");
}

function setupGlobalInteractions() {
  window.addEventListener("scroll", () => {
    header?.classList.toggle("is-scrolled", window.scrollY > 12);
  }, { passive: true });

  menuButton?.addEventListener("click", () => {
    const isOpen = document.body.classList.toggle("menu-open");
    menuButton.setAttribute("aria-expanded", String(isOpen));
    menuOverlay?.setAttribute("aria-hidden", String(!isOpen));
  });

  menuOverlay?.addEventListener("click", (event) => {
    if (event.target.closest("a")) closeMenu();
  });

  window.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });

  window.addEventListener("load", () => {
    setTimeout(() => preloader?.classList.add("is-hidden"), 220);
  });
  setTimeout(() => preloader?.classList.add("is-hidden"), 900);
}

